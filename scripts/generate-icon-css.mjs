import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIconsCSS } from '@iconify/utils';
import { icons as tablerIcons } from '@iconify-json/tabler';

const iconNames = ['brand-github', 'brand-youtube', 'external-link', 'world'];

const css = getIconsCSS(tablerIcons, iconNames, {
	format: 'expanded',
	iconSelector: '.icon--{prefix}--{name}'
});

const output = `/* Generated by npm run icons:build. */\n${css}\n`;

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.join(rootDir, '..', 'src', 'lib', 'styles', 'icons.css');

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, output, 'utf8');
